-- La plantilla de una cotización: o es base del producto, o es del mismo
-- tenant. Un CHECK de fila no puede mirar otra tabla, así que va por trigger.
CREATE OR REPLACE FUNCTION fn_validar_plantilla_tenant() RETURNS TRIGGER AS $$
DECLARE v_tp INTEGER;
BEGIN
    SELECT tenant_id INTO v_tp FROM plantillas_cotizacion WHERE id = NEW.plantilla_id;
    IF v_tp IS NOT NULL AND v_tp <> NEW.tenant_id THEN
        RAISE EXCEPTION 'La plantilla % pertenece a otro tenant', NEW.plantilla_id
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER a_validar_plantilla BEFORE INSERT OR UPDATE OF plantilla_id, tenant_id ON cotizaciones
    FOR EACH ROW EXECUTE FUNCTION fn_validar_plantilla_tenant();



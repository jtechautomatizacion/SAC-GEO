-- ----------------------------------------------------------------------------
-- 1. DOMINIOS (la BD como primera línea de defensa)
-- ----------------------------------------------------------------------------
-- Se usan DOMAIN sobre VARCHAR en vez de ENUM nativo: se leen igual, se
-- validan igual, y son portables si algún día se evalúa otro motor.

-- Máquina de estados de la cotización:
--   borrador → emitida → aceptada | rechazada | cancelada
CREATE DOMAIN dom_estado_cotizacion AS VARCHAR(12)
    CHECK (VALUE IN ('borrador','emitida','aceptada','rechazada','cancelada'));

CREATE DOMAIN dom_unidad AS VARCHAR(10)
    CHECK (VALUE IN ('UND','PUNT.','DÍA','M2','M3','ML','KG','GLB'));

CREATE DOMAIN dom_descuento_tipo AS VARCHAR(12)
    CHECK (VALUE IN ('porcentaje','monto'));

CREATE DOMAIN dom_proveedor_nube AS VARCHAR(20)
    CHECK (VALUE IN ('google_drive','office365'));

CREATE DOMAIN dom_estado_integracion AS VARCHAR(12)
    CHECK (VALUE IN ('activa','revocada','expirada'));

CREATE DOMAIN dom_tipo_documento AS VARCHAR(24)
    CHECK (VALUE IN ('cotizacion_pdf','certificado_ensayo','orden_compra','otro'));

CREATE DOMAIN dom_origen_documento AS VARCHAR(10)
    CHECK (VALUE IN ('local','nube'));

CREATE DOMAIN dom_accion_auditoria AS VARCHAR(8)
    CHECK (VALUE IN ('INSERT','UPDATE','DELETE'));

-- Identificadores formales peruanos. RUC: 11 dígitos, inicia en 10/15/16/17/20.
CREATE DOMAIN dom_ruc AS VARCHAR(11)
    CHECK (VALUE ~ '^(10|15|16|17|20)[0-9]{9}$');

CREATE DOMAIN dom_dni AS VARCHAR(8)
    CHECK (VALUE ~ '^[0-9]{8}$');

CREATE DOMAIN dom_email AS VARCHAR(150)
    CHECK (VALUE ~* '^[^@[:space:]]+@[^@[:space:]]+\.[A-Za-z]{2,}$');

CREATE DOMAIN dom_telefono AS VARCHAR(25)
    CHECK (VALUE ~ '^[-0-9+() ]{6,25}$');

CREATE DOMAIN dom_color_hex AS VARCHAR(7)
    CHECK (VALUE ~ '^#[0-9a-fA-F]{6}$');

-- Dinero del sistema: nunca negativo, siempre 2 decimales.
CREATE DOMAIN dom_monto AS NUMERIC(12,2) CHECK (VALUE >= 0);
CREATE DOMAIN dom_precio AS NUMERIC(10,2) CHECK (VALUE >= 0);


-- ----------------------------------------------------------------------------
-- 2. SEGURIDAD: ROLES Y USUARIOS
-- ----------------------------------------------------------------------------
-- Aquí NO se implementa login ni JWT (eso es fase de backend). Solo queda el
-- modelo listo para soportarlos sin migrar nada después.

-- [GLOBAL] Los 4 roles son del producto, iguales para todos los laboratorios.
CREATE TABLE roles (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(20)  NOT NULL,        -- 'admin','comercial','laboratorio','lectura'
    nombre       VARCHAR(60)  NOT NULL,
    descripcion  VARCHAR(220),
    es_sistema   BOOLEAN      NOT NULL DEFAULT TRUE,   -- rol base: no se elimina
    CONSTRAINT uq_roles_codigo UNIQUE (codigo)
);

-- [TENANT-SCOPED] Cada laboratorio tendrá sus propios usuarios.
-- El usuario id = 1 ('sistema') es la excepción global: es el autor de los
-- seeds y el fallback de auditoría cuando el backend no fijó app.usuario_id.
CREATE TABLE usuarios (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID         NOT NULL DEFAULT gen_random_uuid(),
    nombres           VARCHAR(100) NOT NULL CHECK (btrim(nombres) <> ''),
    apellidos         VARCHAR(100) NOT NULL CHECK (btrim(apellidos) <> ''),
    email             dom_email    NOT NULL,
    rol_id            INTEGER      NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    -- Preparado para autenticación futura. Guarda SOLO un hash (Argon2id o
    -- bcrypt). Jamás una contraseña, jamás un token. NULL = sin acceso aún.
    password_hash     VARCHAR(255),
    ultimo_acceso_en  TIMESTAMPTZ,
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    desactivado_en    TIMESTAMPTZ,
    desactivado_por   INTEGER      REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_por        INTEGER      REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por   INTEGER      REFERENCES usuarios(id) ON DELETE RESTRICT,
    actualizado_en    TIMESTAMPTZ,
    CONSTRAINT uq_usuarios_public_id UNIQUE (public_id),
    -- [MT] Bajo multi-tenant pasa a UNIQUE (tenant_id, lower(email)).
    CONSTRAINT ck_usuarios_desactivado CHECK (activo OR desactivado_en IS NOT NULL)
);
CREATE UNIQUE INDEX uq_usuarios_email ON usuarios (lower(email));


-- ----------------------------------------------------------------------------
-- 3. CLIENTES: EMPRESA (RUC) / CONTACTO / PERSONA NATURAL (DNI)
-- ----------------------------------------------------------------------------
-- Regla de negocio conservada de v2: una cotización pertenece SIEMPRE a una
-- EMPRESA (con o sin contacto) o a una PERSONA NATURAL. Nunca a ambas.
-- v3 agrega que el CONTACTO tiene que ser de ESA empresa (FK compuesta).

-- [TENANT-SCOPED] La cartera de clientes es el activo del laboratorio.
-- Dos laboratorios distintos pueden tener al mismo cliente: bajo multi-tenant
-- el RUC deja de ser único global y pasa a UNIQUE (tenant_id, ruc).
CREATE TABLE empresas (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID         NOT NULL DEFAULT gen_random_uuid(),
    ruc               dom_ruc      NOT NULL,
    razon_social      VARCHAR(200) NOT NULL CHECK (btrim(razon_social) <> ''),
    direccion         VARCHAR(250),
    telefono          dom_telefono,
    email             dom_email,
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_por        INTEGER      NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por   INTEGER      REFERENCES usuarios(id) ON DELETE RESTRICT,
    actualizado_en    TIMESTAMPTZ,
    CONSTRAINT uq_empresas_public_id UNIQUE (public_id),
    CONSTRAINT uq_empresas_ruc       UNIQUE (ruc)          -- [MT] → (tenant_id, ruc)
);

-- [TENANT-SCOPED] Personas que cotizan en nombre de una empresa.
-- uq_contactos_empresa_id existe para poder colgar de ella la FK compuesta
-- de cotizaciones: es lo que impide que una cotización de la Empresa A
-- referencie al contacto de la Empresa B. Es el mismo patrón que se usará
-- para el aislamiento por tenant.
CREATE TABLE contactos (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID         NOT NULL DEFAULT gen_random_uuid(),
    empresa_id        INTEGER      NOT NULL REFERENCES empresas(id) ON DELETE RESTRICT,
    dni               dom_dni,
    nombres           VARCHAR(100) NOT NULL CHECK (btrim(nombres) <> ''),
    apellidos         VARCHAR(100) NOT NULL CHECK (btrim(apellidos) <> ''),
    cargo             VARCHAR(100),
    celular           dom_telefono,
    email             dom_email,
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_por        INTEGER      NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por   INTEGER      REFERENCES usuarios(id) ON DELETE RESTRICT,
    actualizado_en    TIMESTAMPTZ,
    CONSTRAINT uq_contactos_public_id  UNIQUE (public_id),
    CONSTRAINT uq_contactos_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT uq_contactos_empresa_dni UNIQUE (empresa_id, dni)
);

-- [TENANT-SCOPED] Cliente que cotiza con DNI, sin empresa registrada.
CREATE TABLE personas (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID         NOT NULL DEFAULT gen_random_uuid(),
    dni               dom_dni      NOT NULL,
    nombres           VARCHAR(100) NOT NULL CHECK (btrim(nombres) <> ''),
    apellidos         VARCHAR(100) NOT NULL CHECK (btrim(apellidos) <> ''),
    celular           dom_telefono,
    email             dom_email,
    -- Texto libre a propósito: el cliente suele mencionar una empresa que
    -- todavía no está registrada. Si luego se registra, se crea la empresa
    -- y el contacto; esta columna queda como dato histórico de captación.
    empresa_asociada  VARCHAR(200),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_por        INTEGER      NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por   INTEGER      REFERENCES usuarios(id) ON DELETE RESTRICT,
    actualizado_en    TIMESTAMPTZ,
    CONSTRAINT uq_personas_public_id UNIQUE (public_id),
    CONSTRAINT uq_personas_dni       UNIQUE (dni)          -- [MT] → (tenant_id, dni)
);


-- ----------------------------------------------------------------------------
-- 4. CATÁLOGO: CATEGORÍA > SUBCATEGORÍA > ENSAYO (+ PAQUETES)
-- ----------------------------------------------------------------------------
-- Reglas del modelo, todas exigidas por la BD (ver 02_triggers.sql):
--   R1. Jerarquía estricta Categoría (1) → Subcategorías (N) → Ensayos (N).
--       La categoría de un ensayo se deduce de su subcategoría, no se repite.
--   R2. Toda categoría activa tiene al menos una subcategoría activa.
--   R3. Lo que tiene historia no se borra: se desactiva (activo = FALSE).
--   R4. prefijo_codigo (SU, AG, AS, AL) arma el código del ensayo (SU-01) y
--       queda fijo en cuanto la categoría tiene ensayos.
--   R5. Nombres únicos: categoría en todo el catálogo, subcategoría dentro de
--       su categoría, sin distinguir mayúsculas.
--   R6 (v3). El número del código sale de `correlativos`, nunca de MAX()+1,
--       y NO se reutiliza aunque el ensayo se elimine.

-- [TENANT-SCOPED] Cada laboratorio define y tarifa su propio catálogo.
CREATE TABLE categorias_ensayo (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID          NOT NULL DEFAULT gen_random_uuid(),
    -- slug = identificador estable para integraciones y URLs; NO es la PK.
    slug              VARCHAR(40)   NOT NULL CHECK (slug ~ '^[a-z0-9_]{2,40}$'),
    nombre            VARCHAR(40)   NOT NULL CHECK (btrim(nombre) <> ''),
    prefijo_codigo    VARCHAR(3)    NOT NULL CHECK (prefijo_codigo ~ '^[A-Z]{2,3}$'),   -- R4
    icono             VARCHAR(10),
    color_hex         dom_color_hex,
    orden             SMALLINT      NOT NULL DEFAULT 0 CHECK (orden >= 0),
    activo            BOOLEAN       NOT NULL DEFAULT TRUE,                               -- R3
    creado_por        INTEGER       NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_en         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por   INTEGER       REFERENCES usuarios(id) ON DELETE RESTRICT,
    actualizado_en    TIMESTAMPTZ,
    CONSTRAINT uq_categorias_public_id UNIQUE (public_id),
    CONSTRAINT uq_categorias_slug      UNIQUE (slug),             -- [MT] → (tenant_id, slug)
    CONSTRAINT uq_categorias_prefijo   UNIQUE (prefijo_codigo)    -- [MT] → (tenant_id, prefijo_codigo)
);
CREATE UNIQUE INDEX uq_categorias_nombre ON categorias_ensayo (lower(nombre));           -- R5

-- [TENANT-SCOPED]
CREATE TABLE subcategorias_ensayo (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID         NOT NULL DEFAULT gen_random_uuid(),
    categoria_id      INTEGER      NOT NULL REFERENCES categorias_ensayo(id) ON DELETE RESTRICT,
    nombre            VARCHAR(40)  NOT NULL CHECK (btrim(nombre) <> ''),
    orden             SMALLINT     NOT NULL DEFAULT 0 CHECK (orden >= 0),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,                                -- R3
    creado_por        INTEGER      NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por   INTEGER      REFERENCES usuarios(id) ON DELETE RESTRICT,
    actualizado_en    TIMESTAMPTZ,
    CONSTRAINT uq_subcategorias_public_id UNIQUE (public_id),
    -- Necesaria para la FK compuesta de ensayos_catalogo: garantiza que el
    -- ensayo, su subcategoría y su categoría sean coherentes entre sí.
    CONSTRAINT uq_subcategorias_categoria_id UNIQUE (categoria_id, id)
);
CREATE UNIQUE INDEX uq_subcategorias_nombre
    ON subcategorias_ensayo (categoria_id, lower(nombre));                                -- R5

-- [TENANT-SCOPED] El corazón del sistema: cada fila es un servicio vendible.
-- es_paquete = TRUE cuando en realidad es un combo (ver paquete_componentes).
-- El precio del paquete es propio: el laboratorio da descuento por combo.
--
-- categoria_id está DENORMALIZADO a propósito y amarrado con FK compuesta a
-- (categoria_id, subcategoria_id). Motivo: el trigger que valida el prefijo
-- del código y el dashboard por categoría lo consultan en cada fila; sin esta
-- columna harían un JOIN extra y, peor, el código y la categoría podrían
-- desincronizarse al mover una subcategoría.
CREATE TABLE ensayos_catalogo (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID          NOT NULL DEFAULT gen_random_uuid(),
    -- CÓDIGO DE NEGOCIO. No es la PK y no es el id público.
    codigo            VARCHAR(12)   NOT NULL CHECK (codigo ~ '^[A-Z]{2,3}-[0-9]{2,4}$'),
    categoria_id      INTEGER       NOT NULL,
    subcategoria_id   INTEGER       NOT NULL,
    nombre            VARCHAR(220)  NOT NULL CHECK (btrim(nombre) <> ''),
    descripcion       VARCHAR(500),
    unidad            dom_unidad    NOT NULL DEFAULT 'UND',
    norma             VARCHAR(120),
    precio_base       dom_precio    NOT NULL,
    es_paquete        BOOLEAN       NOT NULL DEFAULT FALSE,
    acreditado        BOOLEAN       NOT NULL DEFAULT FALSE,   -- ISO/IEC 17025 vigente HOY
    activo            BOOLEAN       NOT NULL DEFAULT TRUE,
    -- Desde cuándo dejó de ofrecerse. Un auditor ISO 17025 pregunta esto;
    -- por eso es columna y no solo una fila en `auditoria`.
    desactivado_en    TIMESTAMPTZ,
    desactivado_por   INTEGER       REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_por        INTEGER       NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_en         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por   INTEGER       REFERENCES usuarios(id) ON DELETE RESTRICT,
    actualizado_en    TIMESTAMPTZ,
    CONSTRAINT uq_ensayos_public_id UNIQUE (public_id),
    CONSTRAINT uq_ensayos_codigo    UNIQUE (codigo),          -- [MT] → (tenant_id, codigo)
    CONSTRAINT fk_ensayos_subcategoria
        FOREIGN KEY (categoria_id, subcategoria_id)
        REFERENCES subcategorias_ensayo (categoria_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_ensayos_desactivado CHECK (activo OR desactivado_en IS NOT NULL)
);

-- [TENANT-SCOPED] APPEND-ONLY (no se actualiza; ver 02_triggers.sql).
-- Historial de acreditación: cuándo un ensayo ganó o perdió su alcance.
-- Permite responder "¿estaba SU-03 acreditado el 15/03/2024?" sin adivinar.
CREATE TABLE ensayo_acreditacion_historial (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ensayo_id         INTEGER      NOT NULL REFERENCES ensayos_catalogo(id) ON DELETE CASCADE,
    acreditado        BOOLEAN      NOT NULL,
    motivo            VARCHAR(300),
    vigente_desde     DATE         NOT NULL DEFAULT CURRENT_DATE,
    registrado_por    INTEGER      NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    registrado_en     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Dos filas para el mismo ensayo y el mismo día harían ambigua la
    -- reconstrucción histórica. Se permite una por día y por ensayo.
    CONSTRAINT uq_acreditacion_dia UNIQUE (ensayo_id, vigente_desde)
);

-- [TENANT-SCOPED] Composición de los paquetes.
-- P1. Solo un ensayo con es_paquete = TRUE puede tener componentes.
-- P2. Un componente vinculado es un ensayo INDIVIDUAL (no se anidan paquetes)
--     y nunca el propio paquete.
-- P3. El mismo ensayo no se repite dentro de un paquete (se usa `cantidad`).
-- P4. Un paquete creado o editado desde la app lleva al menos 2 componentes
--     vinculados al catálogo (fn_definir_componentes).
-- P5. Los componentes pueden venir de otra categoría (el paquete de cantera
--     de Suelos incluye "Abrasión Los Ángeles" de Concreto).
-- Compatibilidad: los componentes históricos sin ensayo equivalente vendible
-- quedan DESCRIPTIVOS (nombre + norma, ensayo_componente_id NULL).
CREATE TABLE paquete_componentes (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ensayo_id             INTEGER      NOT NULL REFERENCES ensayos_catalogo(id) ON DELETE CASCADE,
    orden                 SMALLINT     NOT NULL DEFAULT 0 CHECK (orden >= 0),
    ensayo_componente_id  INTEGER      REFERENCES ensayos_catalogo(id) ON DELETE RESTRICT,
    cantidad              SMALLINT     NOT NULL DEFAULT 1 CHECK (cantidad BETWEEN 1 AND 999),
    nombre                VARCHAR(200),   -- solo para componentes descriptivos
    norma                 VARCHAR(120),
    CONSTRAINT ck_componente_vinculado_o_descrito
        CHECK (ensayo_componente_id IS NOT NULL OR btrim(COALESCE(nombre,'')) <> ''),
    -- Un componente vinculado no lleva texto propio: su nombre y su norma
    -- salen del ensayo (una sola fuente de verdad).
    CONSTRAINT ck_componente_sin_texto_duplicado
        CHECK (ensayo_componente_id IS NULL OR (nombre IS NULL AND norma IS NULL)),
    CONSTRAINT ck_componente_no_es_el_paquete
        CHECK (ensayo_componente_id IS NULL OR ensayo_componente_id <> ensayo_id)          -- P2
);
CREATE UNIQUE INDEX uq_paquete_componente
    ON paquete_componentes (ensayo_id, ensayo_componente_id)
    WHERE ensayo_componente_id IS NOT NULL;                                                -- P3
CREATE UNIQUE INDEX uq_paquete_componente_orden
    ON paquete_componentes (ensayo_id, orden);


-- ----------------------------------------------------------------------------
-- 5. CORRELATIVOS (FASE 6 de la auditoría)
-- ----------------------------------------------------------------------------
-- Un único lugar para todo número de negocio que deba ser consecutivo.
-- Se consume SOLO con fn_siguiente_correlativo(), que es atómico bajo
-- concurrencia (INSERT ... ON CONFLICT DO UPDATE toma el lock de la fila).
--
-- Por qué NO MAX(codigo)+1:
--   · dos usuarios simultáneos obtienen el mismo número;
--   · si se elimina la última fila, el número se reutiliza y se pierde la
--     unicidad histórica del código;
--   · obliga a recorrer la tabla de datos para emitir un número.
--
-- [HÍBRIDA → TENANT-SCOPED] `clave` ya está diseñada como texto libre para
-- que el tenant entre por PK sin rediseñar nada:
--     hoy   ('cotizacion', 'GLOBAL', '2026')
--     mañana('cotizacion', 'GLOBAL', '2026') + tenant_id en la PK
-- Así Tenant A y Tenant B pueden tener ambos COT-2026-001.
CREATE TABLE correlativos (
    ambito          VARCHAR(20) NOT NULL CHECK (ambito IN ('cotizacion','ensayo')),
    clave           VARCHAR(40) NOT NULL,      -- 'GLOBAL' | prefijo de categoría ('SU')
    periodo         VARCHAR(4)  NOT NULL,      -- '2026' para cotizaciones; '-' si no aplica
    ultimo          INTEGER     NOT NULL DEFAULT 0 CHECK (ultimo >= 0),
    actualizado_en  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (ambito, clave, periodo)       -- [MT] → (tenant_id, ambito, clave, periodo)
);


-- ----------------------------------------------------------------------------
-- 6. PLANTILLAS DE COTIZACIÓN
-- ----------------------------------------------------------------------------
-- [HÍBRIDA] Las 3 plantillas base (Estándar/Premium/Express) son del producto;
-- cada laboratorio podrá editar sus textos y crear las suyas. Bajo
-- multi-tenant: tenant_id NULL = plantilla base del producto.
CREATE TABLE plantillas_cotizacion (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id               UUID        NOT NULL DEFAULT gen_random_uuid(),
    slug                    VARCHAR(30) NOT NULL CHECK (slug ~ '^[a-z0-9_]{2,30}$'),
    nombre                  VARCHAR(60) NOT NULL CHECK (btrim(nombre) <> ''),
    icono                   VARCHAR(10),
    validez_dias_sugerida   SMALLINT    NOT NULL DEFAULT 15
                            CHECK (validez_dias_sugerida BETWEEN 1 AND 365),
    terminos_condiciones    TEXT        NOT NULL CHECK (btrim(terminos_condiciones) <> ''),
    activo                  BOOLEAN     NOT NULL DEFAULT TRUE,
    creado_por              INTEGER     NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    creado_en               TIMESTAMPTZ NOT NULL DEFAULT now(),

-- La plantilla de una cotización: o es base del producto, o es del mismo
-- tenant. Un CHECK de fila no puede mirar otra tabla, así que va por trigger.
CREATE OR REPLACE FUNCTION fn_validar_plantilla_tenant() RETURNS TRIGGER AS $$
DECLARE v_tp INTEGER;
BEGIN
    SELECT tenant_id INTO v_tp FROM plantillas_cotizacion WHERE id = NEW.plantilla_id;

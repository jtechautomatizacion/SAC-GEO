-- Resolución del tenant activo. Sin contexto NO adivina: lanza error.
-- Es lo contrario de fn_app_usuario(), que sí tiene fallback: un cambio sin
-- autor identificado es un bug molesto; una consulta sin tenant identificado
-- es una fuga de datos entre clientes.
CREATE OR REPLACE FUNCTION fn_app_tenant() RETURNS INTEGER AS $$
DECLARE v INTEGER := NULLIF(current_setting('app.tenant_id', TRUE), '')::INTEGER;
BEGIN
    IF v IS NULL THEN
        RAISE EXCEPTION 'No hay tenant en el contexto de la sesión'
            USING ERRCODE = 'insufficient_privilege',
                  HINT = 'El backend debe ejecutar SET LOCAL app.tenant_id antes de cualquier consulta.';
    END IF;
    RETURN v;
END;
$$ LANGUAGE plpgsql STABLE;



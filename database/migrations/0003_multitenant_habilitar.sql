-- ----------------------------------------------------------------------------
-- 6. FUNCIONES CONSCIENTES DEL TENANT
-- ----------------------------------------------------------------------------
-- El correlativo se vuelve por tenant. Nada más cambia en su lógica: sigue
-- siendo un INSERT ... ON CONFLICT DO UPDATE atómico.
CREATE OR REPLACE FUNCTION fn_siguiente_correlativo(
    p_ambito VARCHAR, p_clave VARCHAR, p_periodo VARCHAR
) RETURNS INTEGER AS $$
DECLARE v_valor INTEGER;
BEGIN
    INSERT INTO correlativos (tenant_id, ambito, clave, periodo, ultimo)
    VALUES (fn_app_tenant(), p_ambito, p_clave, p_periodo, 1)
    ON CONFLICT (tenant_id, ambito, clave, periodo)
    DO UPDATE SET ultimo = correlativos.ultimo + 1, actualizado_en = now()
    RETURNING ultimo INTO v_valor;
    RETURN v_valor;
END;
$$ LANGUAGE plpgsql;

-- La fecha de negocio sale de la zona horaria DEL TENANT, no del servidor.
CREATE OR REPLACE FUNCTION fn_hoy_lima() RETURNS DATE AS $$
    SELECT (now() AT TIME ZONE COALESCE(
        (SELECT zona_horaria FROM tenants WHERE id = fn_app_tenant()), 'America/Lima'))::date;
$$ LANGUAGE sql STABLE;
COMMENT ON FUNCTION fn_hoy_lima() IS
    'Conserva el nombre por compatibilidad; ahora resuelve la zona del tenant.';

-- El validador del prefijo del código debe mirar la categoría DEL MISMO tenant.
CREATE OR REPLACE FUNCTION fn_validar_codigo_ensayo() RETURNS TRIGGER AS $$
DECLARE v_prefijo VARCHAR(3);
BEGIN
    SELECT prefijo_codigo INTO v_prefijo FROM categorias_ensayo
     WHERE id = NEW.categoria_id AND tenant_id = NEW.tenant_id;
    IF v_prefijo IS NULL THEN
        RAISE EXCEPTION 'La categoría % no existe en este tenant', NEW.categoria_id
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.codigo !~ ('^' || v_prefijo || '-[0-9]{2,4}$') THEN
        RAISE EXCEPTION 'El código "%" no corresponde a la categoría (debe ser %-NN)', NEW.codigo, v_prefijo
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- La auditoría también se sella con el tenant.
CREATE OR REPLACE FUNCTION fn_auditar() RETURNS TRIGGER AS $$
DECLARE
    v_new JSONB := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END;
    v_old JSONB := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END;
    v_ref JSONB := COALESCE(v_new, v_old);
    v_campos TEXT[];
BEGIN
    IF TG_OP = 'UPDATE' THEN
        SELECT array_agg(k ORDER BY k) INTO v_campos
        FROM jsonb_object_keys(v_new) AS k
        WHERE v_old -> k IS DISTINCT FROM v_new -> k;
        IF v_campos IS NULL OR v_campos <@ ARRAY['actualizado_en','actualizado_por'] THEN
            RETURN NULL;
        END IF;
    END IF;
    INSERT INTO auditoria (tenant_id, tabla, registro_id, registro_public_id, accion,
                           campos_cambiados, datos_anteriores, datos_nuevos, usuario_id, ip_origen)
    VALUES (COALESCE((v_ref->>'tenant_id')::INTEGER, fn_app_tenant()),
            TG_TABLE_NAME, (v_ref->>'id')::BIGINT,
            NULLIF(v_ref->>'public_id','')::UUID, TG_OP, v_campos, v_old, v_new,
            fn_app_usuario(), fn_app_ip());
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

